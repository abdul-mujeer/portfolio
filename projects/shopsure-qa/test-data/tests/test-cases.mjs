const requirementModule = Object.fromEntries(requirements.map((requirement) => [requirement.id, requirement.module]));

/** t(id, requirement, scenario, preconditions, testData, steps, expected, priority, type, result) */
function t(id, requirementId, scenario, preconditions, testData, steps, expected, priority, type, result) {
  return {
    id,
    requirementId,
    module: requirementModule[requirementId] ?? "General",
    scenario,
    preconditions,
    testData,
    steps,
    expected,
    priority,
    type,
    status: result.status,
    actual: result.actual,
    defectId: result.defectId ?? "",
    evidence: result.evidence,
    notes: result.notes ?? "",
  };
}

