/**
 * ShopSure manual test cases — single source of truth for test case IDs and execution records.
 *
 * `ActualResult`, `Status` and `EvidenceLink` are filled from REAL executions performed in this
 * repository (Playwright API/UI suites, SQL checks, Newman run, smoke checks and the recorded manual
 * session). Cases that were not executed say so explicitly and explain why.
 *
 * Status values: Pass | Fail | Blocked | Not Executed
 */
